#!/usr/bin/env python3
"""
make_combined_image.py - Combine bootloader and app.bin into a single initial
flash image (combined.bin, starting at Flash 0x00000).

Layout:
  0x00000-0x0DFFF  Bootloader (.pio/build/lat_bl/firmware.bin, <= 56KB)
  0x0E000-0x0FFFF  Reserved (filled with 0xFF)
  0x10000-         Application (.pio/app.bin, generated by tools/make_app_image.py)
Application end must not exceed 0x70000.
"""
import argparse
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent

BL_MAX_SIZE = 0xE000       # 0x00000-0x0DFFF
APP_OFFSET = 0x10000
APP_END_MAX = 0x70000      # 0x10000 + 0x60000
FILL_BYTE = 0xFF


class CombinedImageError(RuntimeError):
    pass


def build_combined_image(bl_bin: bytes, app_bin: bytes) -> bytearray:
    if len(bl_bin) == 0:
        raise CombinedImageError("bootloader firmware.bin is empty")
    if len(bl_bin) > BL_MAX_SIZE:
        raise CombinedImageError(
            "bootloader is %d bytes, larger than its 56KB window (0x00000-0x0DFFF)" % len(bl_bin))
    if len(app_bin) == 0:
        raise CombinedImageError("app.bin is empty")
    if APP_OFFSET + len(app_bin) > APP_END_MAX:
        raise CombinedImageError(
            "application ends at 0x%X, beyond 0x%X" % (APP_OFFSET + len(app_bin), APP_END_MAX))

    out = bytearray([FILL_BYTE]) * (APP_OFFSET + len(app_bin))
    out[0:len(bl_bin)] = bl_bin
    out[APP_OFFSET:APP_OFFSET + len(app_bin)] = app_bin
    return out


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--bl-bin", type=Path,
                        default=PROJECT_ROOT / ".pio" / "build" / "lat_bl" / "firmware.bin")
    parser.add_argument("--app-bin", type=Path, default=PROJECT_ROOT / ".pio" / "app.bin")
    parser.add_argument("--out", type=Path, default=PROJECT_ROOT / ".pio" / "combined.bin")
    args = parser.parse_args()

    for path in (args.bl_bin, args.app_bin):
        if not path.exists():
            print("[make_combined_image] ERROR: %s not found" % path, file=sys.stderr)
            return 1

    bl_bin = args.bl_bin.read_bytes()
    app_bin = args.app_bin.read_bytes()
    try:
        combined = build_combined_image(bl_bin, app_bin)
    except CombinedImageError as exc:
        print("[make_combined_image] ERROR: %s" % exc, file=sys.stderr)
        return 1

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_bytes(combined)
    print("[make_combined_image] wrote %s (%d bytes): bl=%dB @0x00000, app=%dB @0x%05X"
          % (args.out, len(combined), len(bl_bin), len(app_bin), APP_OFFSET))
    return 0


if __name__ == "__main__":
    sys.exit(main())
